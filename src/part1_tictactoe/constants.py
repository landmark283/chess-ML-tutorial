# -*- coding: utf-8 -*-
"""constants.py —— 全项目共用的符号定义

这个文件故意做得极小。它是"字典"：
别的地方看到 EMPTY / X / O，就到这里查它到底是什么。

为什么单开一个文件？
    如果每个文件都写一遍 `EMPTY = 0`，将来你哪天想把 0 改成 "."，
    就要满项目改一遍，还一定会漏掉一处。
    这类"同一个事实只写一次"的习惯，从第一课就开始养成。
"""

# ---- 棋盘上每个格子里可能装的东西 ----
EMPTY = 0   # 空格
X = 1       # 先手（传统上画叉）
O = 2       # 后手（传统上画圈）

# ---- 棋盘尺寸 ----
SIZE = 3            # 井字棋是 3x3
N_CELLS = SIZE * SIZE   # 一共 9 个格子

# ---- 给人和给测试用的显示符号；索引就是上面的数字 ----
SYMBOLS = ["·", "X", "O"]   # SYMBOLS[EMPTY] == "·"，SYMBOLS[X] == "X"，依此类推

# ---- 4 条连线：3 行 + 3 列 + 2 斜线 ----
# 每条线是 3 个格子编号的元组。井字棋的胜负判定 = 看这 8 条线里有没有一条全是同一个符号。
LINES = (
    (0, 1, 2),  # 第 0 行
    (3, 4, 5),  # 第 1 行
    (6, 7, 8),  # 第 2 行
    (0, 3, 6),  # 第 0 列
    (1, 4, 7),  # 第 1 列
    (2, 5, 8),  # 第 2 列
    (0, 4, 8),  # 主对角线 ↘
    (2, 4, 6),  # 副对角线 ↙
)
